export function numberedOptions(q) {
  const correct = numberLabel(q.commas);
  const alternatives = [];
  const possible = Array.from({ length: q.chunks.length - 1 }, (_, i) => i + 1);
  const falseSpot = possible.find(n => !q.commas.includes(n));
  const candidates = [q.commas.slice(0, -1), falseSpot === undefined ? q.commas.slice(1) : [...q.commas, falseSpot].sort((a,b) => a-b), falseSpot === undefined ? [] : [...q.commas.slice(1), falseSpot].sort((a,b) => a-b)];
  for (let mask = 0; mask < 2 ** possible.length; mask++) candidates.push(possible.filter((n, i) => mask & (1 << i)));
  for (const candidate of candidates) {
    const label = numberLabel(candidate);
    if (label !== correct && !alternatives.some(nums => numberLabel(nums) === label)) alternatives.push(candidate);
  }
  return [q.commas, ...alternatives.slice(0, 3)];
}
const punctuationTask = (q, selectable) => {
  const combinations = selectable ? [] : numberedOptions(q);
  return { parts: q.chunks, gaps: true, selectable, commas: q.commas, optionSpots: Object.fromEntries(combinations.map(nums => [numberLabel(nums), nums])), steps: [{ title: selectable ? 'Отметьте места для запятых и нажмите «Проверить»' : 'Выберите все номера, на месте которых нужна запятая', answer: numberLabel(q.commas), options: combinations.map(numberLabel), explanation: 'С запятыми: ' + fullPunctuation(q) + ' ' + q.explain }] };
};
